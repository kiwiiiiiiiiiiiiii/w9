// ── RESULT ──
function showResult() {
  let correct = 0, wrong = 0, skipped = 0;
  userAnswers.forEach((ans, i) => {
    if (ans === null) skipped++;
    else if (ans === quizData[i].correct) correct++;
    else wrong++;
  });

  const netScore   = parseFloat(((correct * MARKS_CORRECT) + (wrong * MARKS_WRONG)).toFixed(2));
  const percentage = Math.max(0, (netScore / TOTAL_QUESTIONS) * 100);

  statCorrect.textContent      = correct;
  statWrong.textContent        = wrong;
  statUnanswered.textContent   = skipped;
  statCorrectMarks.textContent = (correct * MARKS_CORRECT).toFixed(2);
  statWrongMarks.textContent   = (wrong * 0.25).toFixed(2);
  scoreNumber.textContent      = correct;
  scorePercentage.textContent  = percentage.toFixed(1) + "%";
  netScoreDisplay.textContent  = netScore.toFixed(2);
  netScoreDisplay.style.color  =
    netScore > 0 ? "var(--correct-text)" :
    netScore < 0 ? "var(--wrong-text)" :
    "var(--text-secondary)";

  scoreRemark.textContent =
    percentage >= 80 ? "🏆 उत्कृष्ट! अद्भुत प्रदर्शन!" :
    percentage >= 60 ? "👏 बहुत अच्छा! लगभग महारत हासिल!" :
    percentage >= 40 ? "📚 ठीक है। और अभ्यास करें!" :
    percentage >= 20 ? "⚠️ कमज़ोर। गहन अध्ययन आवश्यक।" :
    "❌ और मेहनत करें — फिर से कोशिश करें!";

  const circumference = 339.292;
  setTimeout(() => {
    ringFill.style.strokeDashoffset = circumference - ((correct / TOTAL_QUESTIONS) * circumference);
  }, 100);

  const svg = ringFill.closest("svg");
  if (!svg.querySelector("defs")) {
    const defs = document.createElementNS("http://www.w3.org/2000/svg", "defs");
    defs.innerHTML = `<linearGradient id="scoreGradient" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="#6366f1"/>
      <stop offset="100%" stop-color="#8b5cf6"/>
    </linearGradient>`;
    svg.prepend(defs);
  }

  resultUserName.textContent = "🎓 " + userName;
  renderReview();
  showScreen(resultScreen);
}

// ── REVIEW ──
function renderReview() {
  reviewList.innerHTML = "";
  const labels = ["A", "B", "C", "D"];
  quizData.forEach((q, i) => {
    const ans       = userAnswers[i];
    const isCorrect = ans !== null && ans === q.correct;
    const isWrong   = ans !== null && ans !== q.correct;
    const item      = document.createElement("div");
    item.className  = "review-item " + (isCorrect ? "review-correct" : isWrong ? "review-wrong" : "review-skipped");
    const statusText  = isCorrect ? `+${MARKS_CORRECT} अंक` : isWrong ? `${MARKS_WRONG} अंक` : "0 अंक";
    const statusClass = isCorrect ? "mark-positive" : isWrong ? "mark-negative" : "mark-zero";
    const statusIcon  = isCorrect ? "✅" : isWrong ? "❌" : "⬜";
    item.innerHTML = `
      <div class="review-q-row">
        <span class="review-q-num">${i + 1}.</span>
        <span class="review-q-text">${q.q}</span>
        <span class="review-mark ${statusClass}">${statusIcon} ${statusText}</span>
      </div>
      <div class="review-options">
        ${q.options.map((opt, oi) => {
          let cls = "review-opt";
          if (oi === q.correct) cls += " opt-correct";
          if (ans === oi && oi !== q.correct) cls += " opt-wrong";
          return `<div class="${cls}"><span class="opt-lbl">${labels[oi]}</span><span>${opt}</span></div>`;
        }).join("")}
      </div>
      <div class="review-explanation"><span class="exp-label">💡 व्याख्या:</span> ${q.explanation}</div>
    `;
    reviewList.appendChild(item);
  });
}

